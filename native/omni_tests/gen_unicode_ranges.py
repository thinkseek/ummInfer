# Generates unicode_ranges.hpp: compact codepoint range tables for the
# properties the Qwen2 PRETOKENIZE_REGEX needs (L, N, whitespace).
# Run on the build host with `python3 gen_unicode_ranges.py > unicode_ranges.hpp`.
import unicodedata
import sys

MAX_CP = 0x10FFFF


def ranges(pred):
    out = []
    start = -1
    for cp in range(MAX_CP + 1):
        if pred(cp):
            if start < 0:
                start = cp
        elif start >= 0:
            out.append((start, cp - 1))
            start = -1
    if start >= 0:
        out.append((start, MAX_CP))
    return out


def is_ws(cp):
    # Unicode White_Space property, the exact set of the Rust regex crate \s.
    if cp in (0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0):
        return True
    return unicodedata.category(chr(cp)) in ("Zs", "Zl", "Zp")


def emit(name, rs):
    print(f"// {len(rs)} ranges, generated by gen_unicode_ranges.py")
    print(f"inline constexpr uint32_t k{name}[][2] = {{")
    for lo, hi in rs:
        print(f"    {{0x{lo:04X}, 0x{hi:04X}}},")
    print("};")
    print()


print("// SPDX-License-Identifier: Apache-2.0")
print("// AUTO-GENERATED by gen_unicode_ranges.py (Python "
      f"{sys.version.split()[0]}, Unicode {unicodedata.unidata_version}). Do not edit.")
print("#pragma once")
print("#include <cstdint>")
print()
emit("LetterRanges", ranges(lambda c: unicodedata.category(chr(c)).startswith("L")))
emit("NumberRanges", ranges(lambda c: unicodedata.category(chr(c)).startswith("N")))
emit("SpaceRanges", ranges(is_ws))
